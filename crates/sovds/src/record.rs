//! The dataset record: one self-describing line per observation cycle, generic
//! over the caller's [`Domain`].
//!
//! A record is both the runtime report of one cycle *and* the durable datum a
//! future analysis or model trains on — one type, one source of truth. The format
//! is a single line of ` key=value` tokens that any tool (`grep`, this parser, a
//! human in ten years) can read. The toolkit owns the framing tokens; the domain
//! owns its observation/annotation tokens (see [`Domain`]).
//!
//! Serialisation writes into any [`core::fmt::Write`] sink, so it needs no
//! allocation and stays `no_std`. Parsing is a boundary guard: hostile input is
//! rejected as a value, never trusted.

use crate::domain::{Accept, Domain, ParseError};
use core::fmt::Write;

/// Monotonic logical time: one tick is one observation cycle. The core never reads
/// a real clock — the caller injects it, which makes every record
/// reproducible in a test.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Default)]
pub struct Tick(pub u64);

impl Tick {
    /// Advance by `n` ticks, saturating instead of overflowing so logical time is
    /// always well defined (no undefined arithmetic).
    #[must_use]
    pub const fn saturating_add(self, n: u64) -> Self {
        Self(self.0.saturating_add(n))
    }
}

/// Where a record came from. Analysis must distinguish observations made live from
/// ones recovered later, and from deliberately synthetic ones (the data
/// carries its own provenance).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Source {
    /// Produced by the live collection loop as it ran.
    Live,
    /// Recovered from a fallback buffer after the fact (the collector was off).
    Backfill,
    /// Generated by a synthetic scenario — never observed on the wire.
    Synthetic,
}

impl Source {
    const fn label(self) -> &'static str {
        match self {
            Source::Live => "live",
            Source::Backfill => "backfill",
            Source::Synthetic => "synth",
        }
    }

    fn parse(s: &str) -> Option<Self> {
        match s {
            "live" => Some(Source::Live),
            "backfill" => Some(Source::Backfill),
            "synth" => Some(Source::Synthetic),
            _ => None,
        }
    }
}

/// A complete record of one observation cycle, generic over the caller's domain.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Record<D: Domain> {
    /// Logical tick within a collection run (resets to 0 at each run start).
    pub tick: Tick,
    /// Wall-clock time (Unix seconds), injected by the caller; `0` when unknown.
    pub wall_time: u64,
    /// Whether the system could actually be observed this cycle (`false` ==
    /// degraded).
    pub probed: bool,
    /// The observation (the domain's telemetry).
    pub obs: D::Obs,
    /// The fault this cycle was classified to (or [`Domain::healthy`]).
    pub class: D::Fault,
    /// Domain-specific extras (e.g. a supervisor's decision).
    pub annot: D::Annot,
    /// Provenance of this record.
    pub source: Source,
    /// Ground-truth label when this cycle's fault was **deliberately injected** —
    /// the class we induced on purpose. `None` for organic operation. Comparing it
    /// to `class` measures detection on real behaviour, not guesswork.
    pub label: Option<D::Fault>,
}

/// Serialize a record as one line (no trailing newline). Deterministic,
/// allocation-free. Layout: framing tokens first, then the domain payload —
/// `t ts probed class src [inject] <obs> <annot>`.
///
/// # Errors
/// Propagates any error from the sink `w`.
pub fn write_record<D: Domain, W: Write>(w: &mut W, r: &Record<D>) -> core::fmt::Result {
    write!(w, "t={}", r.tick.0)?;
    write!(w, " ts={}", r.wall_time)?;
    write!(w, " probed={}", u8::from(r.probed))?;
    write!(w, " class={}", D::fault_label(r.class))?;
    write!(w, " src={}", r.source.label())?;
    if let Some(label) = r.label {
        write!(w, " inject={}", D::fault_label(label))?;
    }
    D::write_obs(w, &r.obs)?;
    D::write_annot(w, &r.annot)
}

/// Parse one serialized line back into a [`Record`], the exact inverse of
/// [`write_record`] and a boundary guard: malformed input is rejected, never
/// trusted. Order-tolerant — tokens may appear in any order, so records
/// written by an older layout still parse.
///
/// # Errors
/// Returns [`ParseError`] on a malformed, incomplete, or unknown-key line.
pub fn parse_record<D: Domain>(line: &str) -> Result<Record<D>, ParseError> {
    let mut tick: Option<Tick> = None;
    let mut wall_time: u64 = 0;
    let mut probed: Option<bool> = None;
    let mut class: Option<D::Fault> = None;
    let mut source = Source::Live;
    let mut label: Option<D::Fault> = None;
    let mut builder = D::Builder::default();

    for token in line.split_whitespace() {
        let (key, value) = token.split_once('=').ok_or(ParseError::BadField)?;
        match key {
            "t" => tick = Some(Tick(parse_u64(value)?)),
            "ts" => wall_time = parse_u64(value)?,
            "probed" => probed = Some(parse_bool(value)?),
            "class" => class = Some(D::parse_fault(value).ok_or(ParseError::BadField)?),
            "src" => source = Source::parse(value).ok_or(ParseError::BadField)?,
            "inject" => label = Some(D::parse_fault(value).ok_or(ParseError::BadField)?),
            // Not a framing key: offer it to the domain.
            other => match D::accept(&mut builder, other, value)? {
                Accept::Consumed => {}
                Accept::Unknown => return Err(ParseError::UnknownKey),
            },
        }
    }

    let (obs, annot) = D::finish(builder)?;
    Ok(Record {
        tick: tick.ok_or(ParseError::MissingField)?,
        wall_time,
        probed: probed.ok_or(ParseError::MissingField)?,
        obs,
        class: class.ok_or(ParseError::MissingField)?,
        annot,
        source,
        label,
    })
}

fn parse_u64(value: &str) -> Result<u64, ParseError> {
    value.parse::<u64>().map_err(|_| ParseError::BadField)
}

fn parse_bool(value: &str) -> Result<bool, ParseError> {
    match value {
        "1" => Ok(true),
        "0" => Ok(false),
        _ => Err(ParseError::BadField),
    }
}

#[cfg(test)]
mod tests {
    use super::{parse_record, write_record, Record, Source, Tick};
    use crate::domain::{Accept, Domain, ParseError};
    use core::fmt;

    // The same minimal "service health" domain used to exercise the trait.
    #[derive(Debug, Clone, Copy, PartialEq, Eq)]
    enum Health {
        Ok,
        Overloaded,
    }
    #[derive(Debug, Clone, Copy, PartialEq, Eq)]
    struct Svc;
    #[derive(Default)]
    struct Builder {
        load: Option<u32>,
        acted: bool,
    }
    impl Domain for Svc {
        type Obs = u32;
        type Fault = Health;
        type Annot = bool;
        type Builder = Builder;
        fn healthy() -> Health {
            Health::Ok
        }
        fn faults() -> &'static [Health] {
            &[Health::Ok, Health::Overloaded]
        }
        fn fault_label(f: Health) -> &'static str {
            match f {
                Health::Ok => "ok",
                Health::Overloaded => "overloaded",
            }
        }
        fn parse_fault(s: &str) -> Option<Health> {
            match s {
                "ok" => Some(Health::Ok),
                "overloaded" => Some(Health::Overloaded),
                _ => None,
            }
        }
        fn write_obs<W: fmt::Write>(w: &mut W, obs: &u32) -> fmt::Result {
            write!(w, " load={obs}")
        }
        fn write_annot<W: fmt::Write>(w: &mut W, annot: &bool) -> fmt::Result {
            write!(w, " acted={}", u8::from(*annot))
        }
        fn accept(b: &mut Builder, key: &str, value: &str) -> Result<Accept, ParseError> {
            match key {
                "load" => {
                    b.load = Some(value.parse().map_err(|_| ParseError::BadField)?);
                    Ok(Accept::Consumed)
                }
                "acted" => {
                    b.acted = value == "1";
                    Ok(Accept::Consumed)
                }
                _ => Ok(Accept::Unknown),
            }
        }
        fn finish(b: Builder) -> Result<(u32, bool), ParseError> {
            Ok((b.load.ok_or(ParseError::MissingField)?, b.acted))
        }
    }

    fn sample() -> Record<Svc> {
        Record {
            tick: Tick(7),
            wall_time: 1_700_000_000,
            probed: true,
            obs: 42,
            class: Health::Ok,
            annot: false,
            source: Source::Live,
            label: None,
        }
    }

    #[test]
    fn round_trips_a_healthy_record() -> Result<(), ParseError> {
        let r = sample();
        let mut line = String::new();
        let _ = write_record(&mut line, &r);
        assert_eq!(
            line,
            "t=7 ts=1700000000 probed=1 class=ok src=live load=42 acted=0"
        );
        assert_eq!(parse_record::<Svc>(&line)?, r);
        Ok(())
    }

    #[test]
    fn round_trips_an_injected_fault_record() -> Result<(), ParseError> {
        let mut r = sample();
        r.class = Health::Overloaded;
        r.annot = true;
        r.source = Source::Backfill;
        r.label = Some(Health::Overloaded);
        let mut line = String::new();
        let _ = write_record(&mut line, &r);
        assert!(line.contains("class=overloaded"));
        assert!(line.contains("inject=overloaded"));
        assert!(line.contains("acted=1"));
        assert_eq!(parse_record::<Svc>(&line)?, r);
        Ok(())
    }

    #[test]
    fn is_order_tolerant_and_defaults_optionals() -> Result<(), ParseError> {
        // A record written in a different token order, with ts/src/inject omitted.
        let parsed = parse_record::<Svc>("probed=1 load=5 class=ok acted=0 t=3")?;
        assert_eq!(parsed.tick, Tick(3));
        assert_eq!(parsed.wall_time, 0);
        assert_eq!(parsed.source, Source::Live);
        assert_eq!(parsed.label, None);
        assert_eq!(parsed.obs, 5);
        Ok(())
    }

    #[test]
    fn rejects_hostile_input() {
        assert_eq!(
            parse_record::<Svc>("no equals here"),
            Err(ParseError::BadField)
        );
        assert_eq!(
            parse_record::<Svc>("t=1 probed=1 class=ok mystery=9 load=1"),
            Err(ParseError::UnknownKey)
        );
        assert_eq!(
            parse_record::<Svc>("t=notanumber"),
            Err(ParseError::BadField)
        );
        // Missing required field (class).
        assert_eq!(
            parse_record::<Svc>("t=1 probed=1 load=1"),
            Err(ParseError::MissingField)
        );
    }
}
