//! The audit / training record: a complete, self-describing snapshot of one
//! supervision cycle, and its sovereign serialization.
//!
//! One [`Record`] is both the runtime report of a cycle *and* the durable datum a
//! future model will train on — one type, one source of truth. The format is
//! defined here, in the core, so it is sovereign and stable for the long haul
//! (longevity): a single line of `key=value` fields that any tool — `grep`, a
//! parser we write later, a human in ten years — can read.
//!
//! Serialization writes into any [`core::fmt::Write`] sink, so it needs no
//! allocation and stays `no_std`: the caller supplies the buffer (a heapless one
//! on-device, a `String` in the file adapter). The record schema itself never
//! touches I/O (the principle).

use crate::domain::{
    Aux, Dns, LatencyMs, NodeHealth, NodeId, Proc, Telemetry, Tick, Tunnel, Wan, WanReach,
    MAX_NODES,
};
use crate::failure::FailureClass;
use crate::fleet::NodeVerdict;
use crate::fsm::{Action, Reason, State};
use core::fmt::Write;

/// What became of the action taken this cycle.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Outcome {
    /// No action was taken (the decision was to observe).
    NotActed,
    /// An action was applied and its post-condition verified.
    Verified,
    /// An action was attempted but could not be verified.
    Unverified,
    /// An action was decided but deliberately not issued (observe-only / dry-run).
    /// Distinct from [`Outcome::NotActed`] (no action was warranted at all) and
    /// never conflated with [`Outcome::Verified`] — the dataset must not learn that
    /// a simulated remedy actually took effect (the principle: honest, invalid states
    /// unrepresentable).
    Simulated,
}

/// Where a record came from. The dataset must distinguish observations made by
/// the live brain from ones recovered later out of the router's fallback buffer:
/// backfilled decisions were never actuated, and analysis/training may weigh the
/// two differently (the principle: the data carries its own provenance).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Source {
    /// Produced by the live supervision loop as it ran.
    Live,
    /// Recovered from the router's RAM buffer after the fact (laptop was off).
    Backfill,
    /// Generated by the canonical fault-scenario suite ([`crate::scenario`]) — a
    /// laboratory episode, never observed on the wire and never actuated. Training
    /// and analysis must weigh it apart from real observations (the principle).
    Synthetic,
}

/// A complete record of one supervision cycle.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Record {
    pub tick: Tick,
    /// Wall-clock time (Unix seconds) the record was produced. Injected by the app
    /// — the core never reads a clock (the principle: agnostic core). `0` when unknown
    /// (records written before timestamps existed). Unlike `tick`, this gives a
    /// single global timeline across collector restarts.
    pub wall_time: u64,
    /// Whether the router could be observed this cycle (`false` == ran degraded).
    pub probed: bool,
    /// The raw observation from the router, before adaptive refinement — the
    /// ground truth a model learns from.
    pub telemetry: Telemetry,
    /// The adaptive verdict on the active path this cycle.
    pub path_verdict: NodeVerdict,
    /// The fault the (refined) observation classified to.
    pub failure: FailureClass,
    /// The state the machine moved into.
    pub state: State,
    pub reason: Reason,
    pub action: Action,
    pub outcome: Outcome,
    /// Provenance of this record (live loop vs. recovered from the buffer).
    pub source: Source,
}

/// Serialize a record as one self-describing line (no trailing newline). The
/// output is deterministic and allocation-free.
///
/// # Errors
/// Propagates any error from the underlying sink `w`.
pub fn write_record<W: Write>(w: &mut W, r: &Record) -> core::fmt::Result {
    write!(w, "t={}", r.tick.0)?;
    write!(w, " ts={}", r.wall_time)?;
    write!(w, " probed={}", u8::from(r.probed))?;
    w.write_str(" wan=")?;
    write_wan(w, r.telemetry.wan)?;
    w.write_str(" sb=")?;
    w.write_str(proc_label(r.telemetry.singbox))?;
    w.write_str(" tun=")?;
    write_tunnel(w, r.telemetry.tunnel)?;
    w.write_str(" dns=")?;
    w.write_str(dns_label(r.telemetry.dns))?;
    w.write_str(" nodes=")?;
    write_nodes(w, &r.telemetry.nodes)?;
    write_aux(w, &r.telemetry.aux)?;
    w.write_str(" verdict=")?;
    w.write_str(verdict_label(r.path_verdict))?;
    w.write_str(" class=")?;
    w.write_str(failure_label(r.failure))?;
    w.write_str(" state=")?;
    write_state(w, r.state)?;
    w.write_str(" reason=")?;
    write_reason(w, r.reason)?;
    w.write_str(" action=")?;
    w.write_str(action_label(r.action))?;
    w.write_str(" outcome=")?;
    w.write_str(outcome_label(r.outcome))?;
    w.write_str(" src=")?;
    w.write_str(source_label(r.source))
}

fn write_wan<W: Write>(w: &mut W, wan: Wan) -> core::fmt::Result {
    match wan {
        Wan::Up { uptime_s } => write!(w, "up:{uptime_s}"),
        Wan::Down => w.write_str("down"),
        Wan::Unknown => w.write_str("unknown"),
    }
}

/// Serialize the per-node latency table as `id:lat` entries (or `id:x` for a node
/// that was not measured), comma-separated, in array order; `-` when the table is
/// empty. Records are expected to fill the table sequentially, so this round-trips.
fn write_nodes<W: Write>(w: &mut W, nodes: &[Option<NodeHealth>; MAX_NODES]) -> core::fmt::Result {
    let mut any = false;
    for node in nodes.iter().flatten() {
        if any {
            w.write_str(",")?;
        }
        any = true;
        match node.latency {
            Some(latency) => write!(w, "{}:{}", node.id.0, latency.0)?,
            None => write!(w, "{}:x", node.id.0)?,
        }
    }
    if !any {
        w.write_str("-")?;
    }
    Ok(())
}

fn write_tunnel<W: Write>(w: &mut W, tunnel: Tunnel) -> core::fmt::Result {
    match tunnel {
        Tunnel::Healthy { latency } => write!(w, "ok:{}", latency.0),
        Tunnel::Degraded { latency } => write!(w, "deg:{}", latency.0),
        Tunnel::Dead => w.write_str("dead"),
        Tunnel::Unknown => w.write_str("unknown"),
    }
}

/// Serialize the auxiliary signals; `-` uniformly encodes "not measured", so the
/// line always carries every key (deterministic layout, the principle) while old
/// readers of the values stay trivial.
fn write_aux<W: Write>(w: &mut W, aux: &Aux) -> core::fmt::Result {
    match aux.wan_reach {
        WanReach::Ok => w.write_str(" wanok=1")?,
        WanReach::Blackhole => w.write_str(" wanok=0")?,
        WanReach::Unknown => w.write_str(" wanok=-")?,
    }
    match aux.load_centi {
        Some(v) => write!(w, " load={v}")?,
        None => w.write_str(" load=-")?,
    }
    match aux.mem_free_kb {
        Some(v) => write!(w, " mem={v}")?,
        None => w.write_str(" mem=-")?,
    }
    match aux.active {
        Some(v) => write!(w, " active={v}"),
        None => w.write_str(" active=-"),
    }
}

fn write_state<W: Write>(w: &mut W, state: State) -> core::fmt::Result {
    match state {
        State::Healthy => w.write_str("healthy"),
        State::Suspect { failing, seen } => {
            write!(w, "suspect:{}:{}", failure_label(failing), seen)
        }
        State::Cooldown {
            failing,
            level,
            until,
        } => {
            write!(
                w,
                "cooldown:{}:{}:{}",
                failure_label(failing),
                level,
                until.0
            )
        }
    }
}

const fn proc_label(p: Proc) -> &'static str {
    match p {
        Proc::Running => "running",
        Proc::Dead => "dead",
        Proc::Unknown => "unknown",
    }
}

const fn dns_label(d: Dns) -> &'static str {
    match d {
        Dns::Ok => "ok",
        Dns::Failing => "failing",
        Dns::Unknown => "unknown",
    }
}

const fn verdict_label(v: NodeVerdict) -> &'static str {
    match v {
        NodeVerdict::Warming => "warming",
        NodeVerdict::Healthy => "healthy",
        NodeVerdict::Slow => "slow",
        NodeVerdict::Throttled => "throttled",
        NodeVerdict::Down => "down",
    }
}

const fn failure_label(f: FailureClass) -> &'static str {
    match f {
        FailureClass::None => "none",
        FailureClass::WanDown => "wan_down",
        FailureClass::SingboxDead => "singbox_dead",
        FailureClass::NodeDead => "node_dead",
        FailureClass::NodeDegraded => "node_degraded",
        FailureClass::DnsFail => "dns_fail",
    }
}

/// Serialize a reason losslessly, including its payload, so it round-trips.
fn write_reason<W: Write>(w: &mut W, reason: Reason) -> core::fmt::Result {
    match reason {
        Reason::Nominal => w.write_str("nominal"),
        Reason::FirstSuspicion(class) => write!(w, "first_suspicion:{}", failure_label(class)),
        Reason::AwaitingConfirmation { failing, seen } => {
            write!(w, "awaiting:{}:{}", failure_label(failing), seen)
        }
        Reason::Recovered => w.write_str("recovered"),
        Reason::Confirmed { failing, level } => {
            write!(w, "confirmed:{}:{}", failure_label(failing), level)
        }
        Reason::CoolingDown => w.write_str("cooling"),
        Reason::Escalated { failing, level } => {
            write!(w, "escalated:{}:{}", failure_label(failing), level)
        }
    }
}

const fn action_label(a: Action) -> &'static str {
    match a {
        Action::Observe => "observe",
        Action::SwitchNode => "switch_node",
        Action::RestartSingbox => "restart_singbox",
        Action::BounceWan => "bounce_wan",
        Action::FailoverBackup => "failover_backup",
        Action::Reboot => "reboot",
    }
}

const fn outcome_label(o: Outcome) -> &'static str {
    match o {
        Outcome::NotActed => "-",
        Outcome::Verified => "verified",
        Outcome::Unverified => "unverified",
        Outcome::Simulated => "dryrun",
    }
}

const fn source_label(s: Source) -> &'static str {
    match s {
        Source::Live => "live",
        Source::Backfill => "backfill",
        Source::Synthetic => "synth",
    }
}

/// Why a serialized record line could not be parsed back. The offending line is
/// the caller's context (the principle): kind plus line is enough to reproduce.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[non_exhaustive]
pub enum ParseError {
    /// A `key=value` token was malformed or a value did not parse.
    BadField,
    /// A required field was absent.
    MissingField,
    /// An unrecognized key was present.
    UnknownKey,
}

/// Parse one serialized line back into a [`Record`]. The exact inverse of
/// [`write_record`], and a boundary guard: any malformed input is rejected rather
/// than trusted (the principle). Note the node table is not serialized, so it parses
/// back empty — everything else round-trips exactly.
///
/// # Errors
/// Returns [`ParseError`] on a malformed, incomplete, or unknown-key line.
pub fn parse_record(line: &str) -> Result<Record, ParseError> {
    let mut tick: Option<Tick> = None;
    let mut probed: Option<bool> = None;
    let mut wan: Option<Wan> = None;
    let mut singbox: Option<Proc> = None;
    let mut tunnel: Option<Tunnel> = None;
    let mut dns: Option<Dns> = None;
    let mut verdict: Option<NodeVerdict> = None;
    let mut failure: Option<FailureClass> = None;
    let mut state: Option<State> = None;
    let mut reason: Option<Reason> = None;
    let mut action: Option<Action> = None;
    let mut outcome: Option<Outcome> = None;
    // Optional and backward-compatible: records written before per-node telemetry
    // simply omit `nodes=`, and parse back with an empty table.
    let mut nodes: [Option<NodeHealth>; MAX_NODES] = [None; MAX_NODES];
    // Optional too: records written before timestamps omit `ts=` and parse as 0.
    let mut wall_time: u64 = 0;
    // Optional: records written before provenance existed default to Live.
    let mut source = Source::Live;
    // Optional: records written before auxiliary signals parse as UNKNOWN.
    let mut aux = Aux::UNKNOWN;

    for token in line.split_whitespace() {
        let (key, value) = token.split_once('=').ok_or(ParseError::BadField)?;
        match key {
            "t" => tick = Some(Tick(parse_u64(value)?)),
            "ts" => wall_time = parse_u64(value)?,
            "probed" => probed = Some(parse_bool(value)?),
            "wan" => wan = Some(parse_wan(value)?),
            "sb" => singbox = Some(parse_proc(value).ok_or(ParseError::BadField)?),
            "tun" => tunnel = Some(parse_tunnel(value)?),
            "dns" => dns = Some(parse_dns(value).ok_or(ParseError::BadField)?),
            "nodes" => nodes = parse_nodes(value)?,
            "verdict" => verdict = Some(parse_verdict(value).ok_or(ParseError::BadField)?),
            "class" => failure = Some(parse_failure(value).ok_or(ParseError::BadField)?),
            "state" => state = Some(parse_state(value)?),
            "reason" => reason = Some(parse_reason(value)?),
            "action" => action = Some(parse_action(value).ok_or(ParseError::BadField)?),
            "outcome" => outcome = Some(parse_outcome(value).ok_or(ParseError::BadField)?),
            "src" => source = parse_source(value).ok_or(ParseError::BadField)?,
            "wanok" => aux.wan_reach = parse_wanok(value)?,
            "load" => aux.load_centi = parse_opt_u32(value)?,
            "mem" => aux.mem_free_kb = parse_opt_u32(value)?,
            "active" => aux.active = parse_opt_u8(value)?,
            _ => return Err(ParseError::UnknownKey),
        }
    }

    Ok(Record {
        tick: tick.ok_or(ParseError::MissingField)?,
        wall_time,
        probed: probed.ok_or(ParseError::MissingField)?,
        telemetry: Telemetry {
            wan: wan.ok_or(ParseError::MissingField)?,
            singbox: singbox.ok_or(ParseError::MissingField)?,
            tunnel: tunnel.ok_or(ParseError::MissingField)?,
            dns: dns.ok_or(ParseError::MissingField)?,
            nodes,
            aux,
        },
        path_verdict: verdict.ok_or(ParseError::MissingField)?,
        failure: failure.ok_or(ParseError::MissingField)?,
        state: state.ok_or(ParseError::MissingField)?,
        reason: reason.ok_or(ParseError::MissingField)?,
        action: action.ok_or(ParseError::MissingField)?,
        outcome: outcome.ok_or(ParseError::MissingField)?,
        source,
    })
}

fn parse_u64(value: &str) -> Result<u64, ParseError> {
    value.parse::<u64>().map_err(|_| ParseError::BadField)
}

fn parse_u8(value: &str) -> Result<u8, ParseError> {
    value.parse::<u8>().map_err(|_| ParseError::BadField)
}

fn parse_u32(value: &str) -> Result<u32, ParseError> {
    value.parse::<u32>().map_err(|_| ParseError::BadField)
}

fn parse_bool(value: &str) -> Result<bool, ParseError> {
    match value {
        "1" => Ok(true),
        "0" => Ok(false),
        _ => Err(ParseError::BadField),
    }
}

fn parse_wan(value: &str) -> Result<Wan, ParseError> {
    match value {
        "down" => Ok(Wan::Down),
        "unknown" => Ok(Wan::Unknown),
        other => {
            let (tag, rest) = other.split_once(':').ok_or(ParseError::BadField)?;
            if tag != "up" {
                return Err(ParseError::BadField);
            }
            Ok(Wan::Up {
                uptime_s: parse_u32(rest)?,
            })
        }
    }
}

fn parse_tunnel(value: &str) -> Result<Tunnel, ParseError> {
    match value {
        "dead" => Ok(Tunnel::Dead),
        "unknown" => Ok(Tunnel::Unknown),
        other => {
            let (tag, rest) = other.split_once(':').ok_or(ParseError::BadField)?;
            let latency = LatencyMs(parse_u32(rest)?);
            match tag {
                "ok" => Ok(Tunnel::Healthy { latency }),
                "deg" => Ok(Tunnel::Degraded { latency }),
                _ => Err(ParseError::BadField),
            }
        }
    }
}

fn parse_state(value: &str) -> Result<State, ParseError> {
    let mut parts = value.split(':');
    match parts.next() {
        Some("healthy") => Ok(State::Healthy),
        Some("suspect") => {
            let failing = next_failure(&mut parts)?;
            let seen = next_u8(&mut parts)?;
            Ok(State::Suspect { failing, seen })
        }
        Some("cooldown") => {
            let failing = next_failure(&mut parts)?;
            let level = next_u8(&mut parts)?;
            let until = Tick(next_u64(&mut parts)?);
            Ok(State::Cooldown {
                failing,
                level,
                until,
            })
        }
        _ => Err(ParseError::BadField),
    }
}

fn parse_reason(value: &str) -> Result<Reason, ParseError> {
    let mut parts = value.split(':');
    match parts.next() {
        Some("nominal") => Ok(Reason::Nominal),
        Some("recovered") => Ok(Reason::Recovered),
        Some("cooling") => Ok(Reason::CoolingDown),
        Some("first_suspicion") => Ok(Reason::FirstSuspicion(next_failure(&mut parts)?)),
        Some("awaiting") => {
            let failing = next_failure(&mut parts)?;
            let seen = next_u8(&mut parts)?;
            Ok(Reason::AwaitingConfirmation { failing, seen })
        }
        Some("confirmed") => {
            let failing = next_failure(&mut parts)?;
            let level = next_u8(&mut parts)?;
            Ok(Reason::Confirmed { failing, level })
        }
        Some("escalated") => {
            let failing = next_failure(&mut parts)?;
            let level = next_u8(&mut parts)?;
            Ok(Reason::Escalated { failing, level })
        }
        _ => Err(ParseError::BadField),
    }
}

fn next_failure<'a>(parts: &mut impl Iterator<Item = &'a str>) -> Result<FailureClass, ParseError> {
    parts
        .next()
        .and_then(parse_failure)
        .ok_or(ParseError::BadField)
}

fn next_u8<'a>(parts: &mut impl Iterator<Item = &'a str>) -> Result<u8, ParseError> {
    match parts.next() {
        Some(s) => parse_u8(s),
        None => Err(ParseError::BadField),
    }
}

fn next_u64<'a>(parts: &mut impl Iterator<Item = &'a str>) -> Result<u64, ParseError> {
    match parts.next() {
        Some(s) => parse_u64(s),
        None => Err(ParseError::BadField),
    }
}

